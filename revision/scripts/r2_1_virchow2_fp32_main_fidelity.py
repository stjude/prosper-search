def derive_probes(inv_rows, tmpf_ids, fp32_ids, table=PROBE_TABLE):
    n = len(inv_rows)
    if n != N_SLIDES:
        raise FidelityError(f'M1.3: #29 has {n} virchow2 rows, expected {N_SLIDES}')
    srt = sorted(inv_rows, key=lambda r: (r['canonical_tiles'], str(r['slide_id'])))
    pos = [0, 1, (n - 1) // 2, (n - 1) // 2 + 1, n - 2, n - 1]
    chosen = [srt[p] for p in pos]
    f16 = [r for r in inv_rows if r['dtype'] == 'float16']
    big16 = max(f16, key=lambda r: (r['canonical_tiles'], str(r['slide_id'])))
    n_big16 = sum(r['canonical_tiles'] == big16['canonical_tiles'] for r in f16)
    if big16['slide_id'] not in {r['slide_id'] for r in chosen}:
        chosen.append(big16)
    if tmpf_ids != fp32_ids:
        raise FidelityError('M1.3: sorted TMPF glob != sorted FP32 glob')
    index = {sid: i + 1 for i, sid in enumerate(tmpf_ids)}
    derived = [(str(r['slide_id']), r['canonical_tiles'], r['dtype'], index.get(str(r['slide_id'])))
               for r in chosen]
    rep = {'n': n, 'positions_0based': pos, 'largest_float16_ties': n_big16,
           'derived': [dict(zip(('slide_id', 'tiles', 'dtype', 'index_1based'), d)) for d in derived],
           'contract_table': [dict(zip(('slide_id', 'tiles', 'dtype', 'index_1based'), d)) for d in table],
           'equal_to_contract_table': tuple(derived) == tuple(table),
           'n_float32': sum(d[2] == 'float32' for d in derived), 'n_float16': sum(d[2] == 'float16' for d in derived)}
    if n_big16 != 1:
        rep['note'] = 'largest float16 tile count is tied; tie broken by str(slide_id) maximum (not in contract)'
    if not rep['equal_to_contract_table']:
        raise FidelityError(f'M1.3: derived probe set {derived} != contract table {table}')
    return rep


