def _str_frame(df):
    df = df.copy()
    df.index = [str(i) for i in df.index]
    df.columns = [str(c) for c in df.columns]
    return df


def compare_frames(mine, ref):
    """Live-cell (both < 1e6) comparison in ref order after str-id alignment; returns stats + pattern equality."""
    mine, ref = _str_frame(mine), _str_frame(ref)
    same_order = list(mine.index) == list(ref.index) and list(mine.columns) == list(ref.columns)
    same_ids = set(mine.index) == set(ref.index) and set(mine.columns) == set(ref.columns)
    if not same_ids:
        return {'same_ids': False, 'same_order': False, 'pattern_equal': False}
    a = mine.loc[list(ref.index), list(ref.columns)].to_numpy()
    b = ref.to_numpy()
    live = (a < SENTINEL) & (b < SENTINEL)
    diff = np.abs(a[live] - b[live])
    rel = diff / np.maximum(np.abs(b[live]), 1e-12)
    return {'same_ids': True, 'same_order': same_order,
            'pattern_equal': bool(np.array_equal(a >= SENTINEL, b >= SENTINEL)),
            'n_nan_mine': int(np.isnan(a).sum()), 'n_nan_ref': int(np.isnan(b).sum()),
            'n_live_published': int((b < SENTINEL).sum()),
            'n_sentinel_mine': int((a >= SENTINEL).sum()), 'n_sentinel_ref': int((b >= SENTINEL).sum()),
            'n_live': int(live.sum()), 'max_abs': float(diff.max()) if diff.size else None,
            'max_rel': float(rel.max()) if rel.size else None,
            'n_differing_cells': int((a != b).sum()), 'exactly_equal': bool(np.array_equal(a, b))}


def rebuild_gate(method, rebuilt_unmasked, rebuilt_masked, pub_unmasked, pub_masked, provenance):
    """Paths in, report out. Gate: sentinel pattern of the rebuilt masked matrix == published masked pattern
    (str ids), the live-cell bar < 1e-6 versus #39/#40, no NaN (masked and unmasked rebuilt) and masked
    n_live == n_live_published (F7). Byte identity / exactness reported, not gated."""
    def load(p):
        with open(p, 'rb') as fh:
            return pickle.load(fh)
    cm = compare_frames(load(rebuilt_masked), load(pub_masked))
    cu = compare_frames(load(rebuilt_unmasked), load(pub_unmasked))
    checks = {'masked_ids_equal': cm['same_ids'], 'masked_pattern_equal': cm['pattern_equal'],
              'masked_live_max_rel_lt_1e-6': cm.get('max_rel') is not None and cm['max_rel'] < BAR_REL,
              # F7: NaN cells drop out of both the bar and the sentinel pattern; gate them explicitly
              'masked_no_nan': cm.get('n_nan_mine') == 0,
              'unmasked_no_nan': cu.get('n_nan_mine') == 0,
              'masked_n_live_eq_published': cm.get('n_live') is not None and cm.get('n_live') == cm.get(
                  'n_live_published')}
    q5 = {'unmasked_exactly_equal': cu.get('exactly_equal'), 'masked_exactly_equal': cm.get('exactly_equal'),
          'unmasked_byte_identical': sha256_file(rebuilt_unmasked) == sha256_file(pub_unmasked),
          'masked_byte_identical': sha256_file(rebuilt_masked) == sha256_file(pub_masked)}
    if not all(q5.values()):
        q5['detail'] = {'unmasked': {k: cu.get(k) for k in ('max_abs', 'max_rel', 'n_differing_cells')},
                        'masked': {k: cm.get(k) for k in ('max_abs', 'max_rel', 'n_differing_cells')}}
    return {'stage': f'M1.2 {method}', 'masked_vs_published': cm, 'unmasked_vs_published': cu,
            'same_patient_pairs_masked': provenance.get('same_patient_pairs_masked'),
            'provenance': provenance, 'q5_exactness': q5, 'checks': checks, 'pass': all(checks.values()),
            'failures': [f'M1.2 {method}: {k}' for k, v in checks.items() if not v]}


