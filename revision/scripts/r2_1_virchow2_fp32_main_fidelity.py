def assemble_report(stage_dir, gate_order=GATE_ORDER):
    gates, first_fail, missing = {}, None, []
    for g in gate_order:
        p = os.path.join(stage_dir, f'{g}.json')
        if not os.path.exists(p):
            missing.append(g)
            if first_fail is None:
                first_fail = f'{g}: missing'
            continue
        d = json.load(open(p))
        gates[g] = {k: d.get(k) for k in ('stage', 'pass', 'failures', 'checks', 'q5_exactness', 'cli_output',
                                          'per_row', 'm7_reproduction', 'masked_vs_published',
                                          'unmasked_vs_published', 'same_patient_pairs_masked') if k in d}
        gates[g]['sha256'] = sha256_file(p)
        if not d.get('pass') and first_fail is None:
            first_fail = f'{g}: ' + '; '.join((d.get('failures') or ['pass is false'])[:3])
    failed_elements = []
    fe = os.path.join(stage_dir, 'failed_elements.jsonl')
    if os.path.exists(fe):
        failed_elements = [json.loads(x) for x in open(fe) if x.strip()]
        if failed_elements and first_fail is None:
            first_fail = f'failed_elements.jsonl: {len(failed_elements)} element(s) failed (no eligible retry)'
    rep = {'schema': 'r2_1_virchow2_fp32_main.fidelity_report.v1', 'gates': gates, 'missing': missing,
           'failed_elements': failed_elements, 'all_pass': first_fail is None, 'first_failing_gate': first_fail}
    return rep


def write_marker(stage_dir, rep):
    for name in ('COMPLETE', 'FAILED'):
        if os.path.lexists(os.path.join(stage_dir, name)):
            raise FidelityError(f'{name} already exists in {stage_dir}')
    write_json_new(os.path.join(stage_dir, 'FIDELITY_REPORT.json'), rep)
    name = 'COMPLETE' if rep['all_pass'] else 'FAILED'
    with open(os.path.join(stage_dir, name), 'x') as fh:
        fh.write(json.dumps({'first_failing_gate': rep['first_failing_gate'],
                             'fidelity_report_sha256': sha256_file(os.path.join(stage_dir, 'FIDELITY_REPORT.json'))},
                            sort_keys=True) + '\n')
    return name


