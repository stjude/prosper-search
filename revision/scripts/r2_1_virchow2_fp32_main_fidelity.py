_LSF_PATTERNS = {
    'exit_code': re.compile(r'^Exited with exit code (\d+)\.', re.M),
    'run_time_s': re.compile(r'^\s*Run time :\s+(\d+) sec\.', re.M),
    'max_memory_mb': re.compile(r'^\s*Max Memory :\s+([\d.]+) MB', re.M),
    'host': re.compile(r'^Job was executed on host\(s\) <(?:\d+\*)?([^>]+)>, in queue <([^>]+)>', re.M),
    'term': re.compile(r'^(TERM_[A-Z_]+):', re.M),
    'job': re.compile(r'^Subject: Job (\d+)(?:\[(\d+)\])?:', re.M),
}


def parse_lsf_out(text):
    """LSF -oo epilogue fields. `rc` is 0 for 'Successfully completed.', the exit code otherwise, None if the
    epilogue is absent (job still running or killed without a report)."""
    d = {'rc': None, 'run_time_s': None, 'max_memory_mb': None, 'host': None, 'queue': None, 'term_reason': None,
         'job_id': None, 'job_index': None, 'epilogue': False}
    if re.search(r'^Successfully completed\.', text, re.M):
        d['rc'], d['epilogue'] = 0, True
    m = _LSF_PATTERNS['exit_code'].search(text)
    if m:
        d['rc'], d['epilogue'] = int(m.group(1)), True
    for key in ('run_time_s',):
        m = _LSF_PATTERNS[key].search(text)
        d[key] = int(m.group(1)) if m else None
    m = _LSF_PATTERNS['max_memory_mb'].search(text)
    d['max_memory_mb'] = float(m.group(1)) if m else None
    m = _LSF_PATTERNS['host'].search(text)
    if m:
        d['host'], d['queue'] = m.group(1), m.group(2)
    m = _LSF_PATTERNS['term'].search(text)
    d['term_reason'] = m.group(1) if m else None
    m = _LSF_PATTERNS['job'].search(text)
    if m:
        d['job_id'] = m.group(1)
        d['job_index'] = m.group(2)
    return d


def program_stdout(text):
    """The program's own stdout: the part above LSF's 'Sender: LSF System' mail header (prosper_job.sh does not
    redirect; LSF appends its report after the program output)."""
    i = text.find('\nSender: LSF System')
    if text.startswith('Sender: LSF System'):
        i = 0
    return text if i < 0 else text[:i]


def lsf_logs(stage_dir, jobname, kind):
    """Files `<stage>/lsf/<jobname>.<jobid>_<index>.{out,err}` (submit script naming, %J_%I)."""
    pat = os.path.join(stage_dir, 'lsf', f'{jobname}.*_*.{kind}')
    out = []
    rx = re.compile(re.escape(jobname) + r'\.(\d+)_(\d+)\.' + kind + '$')
    for p in sorted(glob.glob(pat)):
        m = rx.search(os.path.basename(p))
        if m:
            out.append((int(m.group(1)), int(m.group(2)), p))
    return sorted(out)


def latest_attempts(stage_dir, jobname, kind='out'):
    """{index: (job_id, path)} for the highest job id per array index (the M0.5 retry supersedes the first)."""
    d = {}
    for jid, idx, p in lsf_logs(stage_dir, jobname, kind):
        if idx not in d or jid > d[idx][0]:
            d[idx] = (jid, p)
    return d


def stderr_census(stage_dir, jobnames):
    """m5: count census-pattern lines per element stderr. Returns rows (jobname, job_id, index, counts, the
    numItermax-bearing lines' row ids if any)."""
    rows = []
    for jn in jobnames:
        for jid, idx, p in lsf_logs(stage_dir, jn, 'err'):
            counts = {k: 0 for k in CENSUS_KEYS}
            nit = []
            with open(p, errors='replace') as fh:
                for line in fh:
                    if not CENSUS_PATTERN.search(line):
                        continue
                    for k in CENSUS_KEYS:
                        if k in line:
                            counts[k] += 1
                    if 'numItermax' in line:
                        nit.append(line.strip()[:300])
            rows.append({'job': jn, 'job_id': jid, 'index': idx, 'file': p, **counts,
                         'numItermax_lines': nit})
    return rows


def write_census_tsv(path, rows):
    hdr = ('job', 'job_id', 'index') + CENSUS_KEYS + ('file',)
    lines = ['\t'.join(hdr)] + ['\t'.join(str(r[h]) for h in hdr) for r in rows]
    if os.path.lexists(path):
        raise FidelityError(f'refusing to overwrite {path}')
    with open(path, 'x') as fh:
        fh.write('\n'.join(lines) + '\n')


def failed_stdout_lines(stage_dir, jobname):
    hits = []
    for jid, idx, p in lsf_logs(stage_dir, jobname, 'out'):
        with open(p, errors='replace') as fh:
            for line in program_stdout(fh.read()).splitlines():
                if 'FAILED' in line:
                    hits.append({'job_id': jid, 'index': idx, 'line': line.strip()[:300]})
    return hits


def parse_cli_json_and_verdict(stdout_text):
    """The frozen fidelity modes print one indented JSON object then `FIDELITY: PASS|FAIL`."""
    txt = program_stdout(stdout_text)
    m = list(re.finditer(r'^FIDELITY: (PASS|FAIL)\s*$', txt, re.M))
    if len(m) != 1:
        raise FidelityError(f'expected exactly one FIDELITY line, found {len(m)}')
    head = txt[:m[0].start()]
    start = head.rfind('\n{')
    start = 0 if head.startswith('{') and start < 0 else start + 1
    if start < 0 or not head[start:].lstrip().startswith('{'):
        raise FidelityError('no JSON block before the FIDELITY line')
    obj = json.loads(head[start:])
    return obj, m[0].group(1)


