def sha256_file(p, chunk=1 << 22):
    h = hashlib.sha256()
    with open(p, 'rb') as fh:
        for b in iter(lambda: fh.read(chunk), b''):
            h.update(b)
    return h.hexdigest()


def binding(p, expected=None, src=None):
    d = {'path': p, 'size': os.path.getsize(p), 'sha256': sha256_file(p)}
    if expected is not None:
        d['expected_sha256'] = expected
        d['match'] = d['sha256'] == expected
    if src is not None:
        d['src'] = src
    return d


def require_binding(p, expected, label):
    b = binding(p, expected)
    if not b['match']:
        raise FidelityError(f'M0.3: sha256 mismatch for {label} {p}: {b["sha256"]} != {expected}')
    return b


def write_json_new(path, obj):
    if os.path.lexists(path):
        raise FidelityError(f'refusing to overwrite {path}')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'x') as fh:
        json.dump(obj, fh, indent=2, sort_keys=True, default=_json_default)
        fh.write('\n')


def _json_default(o):
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating,)):
        return float(o)
    if isinstance(o, np.ndarray):
        return o.tolist()
    raise TypeError(type(o))


