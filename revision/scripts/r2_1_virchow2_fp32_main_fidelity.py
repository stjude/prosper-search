EXPECTED_NEW_SCHEMA = 'run_002_expected_new/1'      # ADDENDUM_002 F1b: analyst-authored run_002 output allowlist


def relpath_glob_match(pattern, rel):
    """ADDENDUM_002 F1b glob semantics on '/'-separated relpaths. Pattern and path are split on '/'; a component
    that is exactly `**` matches zero or more whole components, except a TRAILING `**`, which matches one or more
    (`a/**` = every path strictly below a, never `a` itself; same as INIT_RUN_002_EXCLUDE's trailing '/**'). Every
    other component is matched with fnmatch.fnmatchcase (`*`, `?`, `[...]`; case-sensitive; `*` also matches a
    leading '.'), so it never crosses '/'. No brace expansion."""
    pp, rp = pattern.split('/'), rel.split('/')

    def m(i, j):
        if i == len(pp):
            return j == len(rp)
        if pp[i] == '**':
            if i == len(pp) - 1:
                return j < len(rp)
            return any(m(i + 1, k) for k in range(j, len(rp) + 1))
        return j < len(rp) and fnmatch.fnmatchcase(rp[j], pp[i]) and m(i + 1, j + 1)
    return m(0, 0)


def load_expected_new(path):
    """ADDENDUM_002 F1b: read the allowlist JSON exactly once; returns (globs, {path, sha256, n_globs}). The file must
    be exactly {"schema": "run_002_expected_new/1", "globs": [<non-empty str>, ...]}; a glob must be a relative
    '/'-separated pattern without empty, '.' or '..' components and without braces (expand them explicitly)."""
    try:
        with open(path, 'rb') as fh:
            data = fh.read()
        doc = json.loads(data)
    except (OSError, ValueError) as e:
        raise FidelityError(f'expected-new {path} unreadable: {e}')
    if not isinstance(doc, dict) or set(doc) != {'schema', 'globs'} or doc['schema'] != EXPECTED_NEW_SCHEMA:
        raise FidelityError(f'expected-new {path}: must be exactly {{"schema": "{EXPECTED_NEW_SCHEMA}", "globs": '
                            '[...]}')
    globs = doc['globs']
    if not isinstance(globs, list) or not globs:
        raise FidelityError(f'expected-new {path}: globs must be a non-empty list')
    for g in globs:
        if not isinstance(g, str) or not g or g.startswith('/') or '{' in g or '}' in g or any(
                c in ('', '.', '..') for c in g.split('/')):
            raise FidelityError(f'expected-new {path}: invalid glob {g!r}')
    return list(globs), {'path': os.path.abspath(path), 'sha256': hashlib.sha256(data).hexdigest(),
                         'n_globs': len(globs)}


def _kind(st):
    if stat.S_ISREG(st.st_mode):
        return 'regular'
    if stat.S_ISLNK(st.st_mode):
        return 'symlink'
    if stat.S_ISDIR(st.st_mode):
        return 'directory'
    return 'other'


def _walk_stage(stage_dir):
    """Every entry below stage_dir as (relpath, lstat); directories are descended, symlinks never followed."""
    out, stack = [], ['']
    while stack:
        rel_dir = stack.pop()
        with os.scandir(os.path.join(stage_dir, rel_dir) if rel_dir else stage_dir) as it:
            for de in it:
                rel = f'{rel_dir}/{de.name}' if rel_dir else de.name
                st = os.lstat(de.path)
                out.append((rel, st))
                if stat.S_ISDIR(st.st_mode):
                    stack.append(rel)
    return sorted(out, key=lambda x: x[0])


def check_lineage(stage_dir, lineage_name=LINEAGE_002, excluded_may_be_regenerated=False, expected_new=None):
    """C1/F1 (impl_004 review): re-hash every file listed in <stage_dir>/<lineage_name> (default LINEAGE_002.json):
    the destination against sha256_dest, the source against sha256_source, and each excluded source file against its
    recorded sha256. Returns a record with `pass`; raises FidelityError only if the lineage file is missing or
    unreadable (or the --expected-new allowlist is unreadable/invalid or given for a non-run-lineage record).
    ADDENDUM_003: every rule below that names run_002 applies to any run-lineage record (schema in
    RUN_LINEAGE_SCHEMAS: LINEAGE_RUN_002.json of run_002 and LINEAGE_RUN_003.json of run_003, whose source is
    run_002); "run_001" then reads "the lineage source". A run_003 record must carry `excluded_patterns` (only the
    run_002 schema falls back to INIT_RUN_002_EXCLUDE). The exempt lineage file is always the stage's own
    `lineage_name` at top level; a lineage file carried from the source stage (run_003/LINEAGE_RUN_002.json) is an
    ordinary listed file and is hashed.
    AMENDMENT_004 (LINEAGE_RUN_002.json, schema LINEAGE_RUN_002_SCHEMA) additionally:
      - `append_only` entries (journal.jsonl etc.): the destination must start with the recorded bytes (its first
        `size` bytes hash to sha256_dest; appended bytes are reported); the source must still match exactly;
      - every excluded path (and excluded subtree) must be absent from the destination. With
        `excluded_may_be_regenerated` (after the run_002 m3_gates job has written its own outputs) a present
        excluded path is accepted only if it is a regular non-symlink file with st_nlink == 1 (so it shares no inode
        with run_001 or anything else), not the run_001 inode and not byte-identical to the run_001 file; a
        directory, symlink or other non-regular entry there is `dest_excluded_not_regular` (ADDENDUM_002 F2).
    ADDENDUM_002 F1 (run_002 lineage only): the destination is walked (symlinks never followed). Every walked
    regular file that is not listed in `files`, not a recorded excluded path, not the top-level lineage file itself
    is classified: matching the lineage-recorded `excluded_patterns` -> strict mode `dest_excluded_present`, relaxed
    mode the F2 checks above (counted in `n_regenerated_new`); else matching an `expected_new` allowlist glob
    (load_expected_new; relpath_glob_match semantics) -> admitted (`n_allowed_new`); else `unlisted_file`. Without
    `expected_new` no unlisted file is admitted in either mode. A symlink/other entry at an excluded or allowlisted
    name, or a directory at a recorded excluded file path or matching such a pattern whose last component is not
    `**`, is `dest_excluded_not_regular`; any other symlink/other entry is `unlisted_file`. Directories are otherwise
    allowed (their files are checked individually). The LINEAGE_002 (fidelity_002) check is unchanged (no walk).
    ADDENDUM_003 (run-lineage records): `lineage_name` must be the schema's own file name (RUN_LINEAGES) and the
    record's `dest_dir` must be `stage_dir` (os.path.samefile), else `lineage_name_schema_mismatch` /
    `lineage_dest_dir_mismatch`."""
    lp = os.path.join(stage_dir, lineage_name)
    if not os.path.isfile(lp):
        raise FidelityError(f'lineage-check: {lp} missing')
    try:
        lin = json.load(open(lp))
        files, src, excl = lin['files'], lin['source_dir'], lin['excluded']
        schema = lin.get('schema')
        run002 = schema in RUN_LINEAGE_SCHEMAS          # ADDENDUM_003: any run-lineage stage (run_002, run_003)
        excl_dirs = lin.get('excluded_dirs', []) if run002 else []
        if not run002:
            excl_pats = []
        elif schema == LINEAGE_RUN_002_SCHEMA:
            excl_pats = list(lin.get('excluded_patterns', INIT_RUN_002_EXCLUDE))
        else:
            excl_pats = list(lin['excluded_patterns'])
        if not all(isinstance(x, str) for x in excl_pats):
            raise TypeError('excluded_patterns must be strings')
    except (ValueError, KeyError, TypeError, AttributeError) as e:
        raise FidelityError(f'lineage-check: {lp} unreadable: {e}')
    if expected_new is not None and not run002:
        raise FidelityError('lineage-check: --expected-new applies only to a run-lineage stage '
                            f'(schema one of {", ".join(RUN_LINEAGE_SCHEMAS)})')
    allow, allow_rec = load_expected_new(expected_new) if expected_new is not None else ([], None)
    mism, appended = [], []
    if run002:
        # ADDENDUM_003: a run-lineage record is checked only as its own stage's lineage (a run_002 record carried
        # into run_003 is an ordinary listed file there, not a lineage to check run_003 against)
        want_name = {s_: n for n, s_ in RUN_LINEAGES.values()}[schema]
        if lineage_name != want_name:
            mism.append({'role': 'lineage_name_schema_mismatch', 'path': lineage_name, 'file': lp,
                         'expected': want_name, 'actual': lineage_name})
        dd = lin.get('dest_dir')
        try:
            same = isinstance(dd, str) and os.path.samefile(dd, stage_dir)
        except OSError:
            same = False
        if not same:
            mism.append({'role': 'lineage_dest_dir_mismatch', 'path': lineage_name, 'file': lp,
                         'expected': os.path.abspath(stage_dir), 'actual': dd})

    def chk(role, rel, path, want):
        if not os.path.isfile(path) or os.path.islink(path):
            mism.append({'role': role, 'path': rel, 'file': path, 'expected': want, 'actual': None,
                         'error': 'missing or not a regular file'})
            return
        got = sha256_file(path)
        if got != want:
            mism.append({'role': role, 'path': rel, 'file': path, 'expected': want, 'actual': got})

    def chk_prefix(rel, path, want, size):
        if not os.path.isfile(path) or os.path.islink(path):
            mism.append({'role': 'dest_append_only', 'path': rel, 'file': path, 'expected': want, 'actual': None,
                         'error': 'missing or not a regular file'})
            return
        cur = os.path.getsize(path)
        h = hashlib.sha256()
        with open(path, 'rb') as fh:
            left = size
            while left > 0:
                b = fh.read(min(left, 1 << 22))
                if not b:
                    break
                h.update(b)
                left -= len(b)
        got = h.hexdigest()
        if cur < size or got != want:
            mism.append({'role': 'dest_append_only', 'path': rel, 'file': path, 'expected': want, 'actual': got,
                         'error': f'recorded {size}-byte prefix not intact (current size {cur})'})
        elif cur > size:
            appended.append({'path': rel, 'recorded_size': size, 'current_size': cur})

    def regenerated(rel, dp, st, sp, recorded_sha):
        """F2 (relaxed mode): None if the present excluded-name entry is an acceptable regenerated output, else the
        mismatch record."""
        kind = _kind(st)
        if kind != 'regular':
            return {'role': 'dest_excluded_not_regular', 'path': rel, 'file': dp, 'kind': kind,
                    'expected': 'regular non-symlink file', 'actual': kind}
        why = None
        try:
            ss = os.stat(sp)
            if (ss.st_dev, ss.st_ino) == (st.st_dev, st.st_ino):
                why = 'run_001 inode'
        except (FileNotFoundError, NotADirectoryError):
            pass
        if why is None and st.st_nlink > 1:
            why = f'st_nlink={st.st_nlink} (inode shared with another path)'
        if why is None and recorded_sha is not None and sha256_file(dp) == recorded_sha:
            why = 'byte-identical to run_001'
        if why is None:
            return None
        return {'role': 'dest_excluded_carried_over', 'path': rel, 'file': dp,
                'expected': 'regenerated (new inode, st_nlink 1, different bytes)', 'actual': why}

    n_hashed = 0
    for e in files:
        if run002 and e.get('append_only'):
            chk_prefix(e['path'], os.path.join(stage_dir, e['path']), e['sha256_dest'], e['size'])
        else:
            chk('dest', e['path'], os.path.join(stage_dir, e['path']), e['sha256_dest'])
        chk('source', e['path'], os.path.join(src, e['path']), e['sha256_source'])
        n_hashed += 2
    for e in excl:
        chk('source_excluded', e['path'], os.path.join(src, e['path']), e['sha256'])
        n_hashed += 1
    n_excl_dest = 0
    n_unlisted = n_allowed_new = n_regenerated_new = n_walked = 0
    if run002:
        for e in excl:
            dp, sp = os.path.join(stage_dir, e['path']), os.path.join(src, e['path'])
            n_excl_dest += 1
            if not os.path.lexists(dp):
                continue
            if not excluded_may_be_regenerated:
                mism.append({'role': 'dest_excluded_present', 'path': e['path'], 'file': dp,
                             'expected': None, 'actual': 'present'})
                continue
            bad = regenerated(e['path'], dp, os.lstat(dp), sp, e['sha256'])
            if bad is not None:
                mism.append(bad)
        if not excluded_may_be_regenerated:
            for d in excl_dirs:
                n_excl_dest += 1
                if os.path.lexists(os.path.join(stage_dir, d)):
                    mism.append({'role': 'dest_excluded_present', 'path': d, 'file': os.path.join(stage_dir, d),
                                 'expected': None, 'actual': 'present'})
        # ADDENDUM_002 F1: walk the destination for files the lineage does not account for
        listed = {e['path'] for e in files}
        excl_paths = {e['path'] for e in excl}

        def is_excl(rel):
            return any(relpath_glob_match(p, rel) for p in excl_pats)

        def is_allowed(rel):
            return any(relpath_glob_match(g, rel) for g in allow)

        def names_file(rel):
            """rel matches an excluded/allowlisted pattern that names a file (last component is not `**`)."""
            return any(p.split('/')[-1] != '**' and relpath_glob_match(p, rel) for p in excl_pats + allow)

        for rel, st in _walk_stage(stage_dir):
            if rel in listed or rel in excl_paths or rel == lineage_name:
                continue
            dp = os.path.join(stage_dir, rel)
            kind = _kind(st)
            if kind == 'directory':
                if names_file(rel):
                    mism.append({'role': 'dest_excluded_not_regular', 'path': rel, 'file': dp, 'kind': kind,
                                 'expected': 'regular non-symlink file', 'actual': kind})
                continue
            n_walked += 1
            if kind != 'regular':
                if is_excl(rel) or is_allowed(rel) or rel in excl_dirs:
                    mism.append({'role': 'dest_excluded_not_regular', 'path': rel, 'file': dp, 'kind': kind,
                                 'expected': 'regular non-symlink file', 'actual': kind})
                else:
                    n_unlisted += 1
                    mism.append({'role': 'unlisted_file', 'path': rel, 'file': dp, 'kind': kind,
                                 'expected': None, 'actual': 'present'})
                continue
            if is_excl(rel):
                if not excluded_may_be_regenerated:
                    mism.append({'role': 'dest_excluded_present', 'path': rel, 'file': dp,
                                 'expected': None, 'actual': 'present'})
                    continue
                bad = regenerated(rel, dp, st, os.path.join(src, rel), None)
                if bad is not None:
                    mism.append(bad)
                else:
                    n_regenerated_new += 1
            elif is_allowed(rel):
                n_allowed_new += 1
            else:
                n_unlisted += 1
                mism.append({'role': 'unlisted_file', 'path': rel, 'file': dp, 'kind': kind,
                             'expected': None, 'actual': 'present'})
    rec = {'lineage': binding(lp), 'stage_dir': os.path.abspath(stage_dir), 'source_dir': src,
           'n_files': len(files), 'n_excluded': len(excl), 'n_hashed': n_hashed, 'mismatches': mism,
           'pass': not mism}
    if run002:
        rec.update({'lineage_file': lineage_name, 'n_excluded_dest_checked': n_excl_dest,
                    'excluded_may_be_regenerated': bool(excluded_may_be_regenerated),
                    'append_only_appended': appended, 'n_walked_unrecorded': n_walked, 'n_unlisted': n_unlisted,
                    'n_allowed_new': n_allowed_new, 'n_regenerated_new': n_regenerated_new,
                    'expected_new': allow_rec})
    return rec


