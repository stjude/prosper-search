def init_run_003(src=None, dst=None, addendum=None, addendum_sha=ADDENDUM_003_SHA, link=os.link, copy=False,
                 exclude=INIT_RUN_003_EXCLUDE):
    """ADDENDUM_003 §2.1/2.2: create a NEW `dst` (run_003) from frozen `src` (run_002) with init_run: `exclude`
    (default INIT_RUN_003_EXCLUDE), INIT_RUN_003_COPY, dst/LINEAGE_RUN_003.json binding ADDENDUM_003 (`addendum`),
    run_002/FAILED (`run_002_failed`) and run_002/LINEAGE_RUN_002.json (`run_002_lineage`, with its schema), so the
    chain run_001 -> run_002 -> run_003 is explicit. Refuses if run_003 exists, run_002/FAILED or
    run_002/LINEAGE_RUN_002.json is absent, or the carried lineage file is not a LINEAGE_RUN_002_SCHEMA record."""
    src = os.path.abspath(src or RUN_DIR_002)
    dst = os.path.abspath(dst or RUN_DIR_003)
    addendum = addendum or ADDENDUM_003
    label = 'init-run'
    if os.path.lexists(dst):
        raise FidelityError(f'{label}: {dst} already exists (refusing)')
    if os.path.islink(src) or not os.path.isdir(src):
        raise FidelityError(f'{label}: source {src} is not a directory')
    failed = os.path.join(src, 'FAILED')
    if os.path.islink(failed) or not os.path.isfile(failed):
        raise FidelityError(f'{label}: {failed} absent; there is nothing to retry (refusing)')
    src_lin = os.path.join(src, LINEAGE_RUN_002)
    if os.path.islink(src_lin) or not os.path.isfile(src_lin):
        raise FidelityError(f'{label}: {src_lin} absent; the source stage has no lineage record (refusing)')
    try:
        src_schema = json.load(open(src_lin)).get('schema')
    except (ValueError, AttributeError) as e:
        raise FidelityError(f'{label}: {src_lin} unreadable: {e}')
    if src_schema != LINEAGE_RUN_002_SCHEMA:
        raise FidelityError(f'{label}: {src_lin} schema {src_schema!r} != {LINEAGE_RUN_002_SCHEMA}')
    exclude = tuple(exclude)
    if not exclude or not all(isinstance(x, str) and x and not x.startswith('/') and
                              all(c not in ('', '.', '..') for c in x.split('/')) for x in exclude):
        raise FidelityError(f'{label}: invalid exclude pattern list {exclude!r}')
    if any(run_002_excluded(r, exclude) for r in (LINEAGE_RUN_002,) + tuple(INIT_RUN_003_COPY)):
        raise FidelityError(f'{label}: an exclude pattern matches {LINEAGE_RUN_002} or an append-only state file')
    add_b = require_binding(addendum, addendum_sha, 'ADDENDUM_003')
    bindings = {'addendum': {'path': add_b['path'], 'sha256': add_b['sha256']},
                'run_002_failed': {'path': failed, 'sha256': sha256_file(failed)},
                'run_002_lineage': {'path': src_lin, 'sha256': sha256_file(src_lin), 'schema': src_schema}}
    if exclude != INIT_RUN_003_EXCLUDE:
        bindings['exclude_override'] = {'default': list(INIT_RUN_003_EXCLUDE), 'used': list(exclude)}
    return init_run(src, dst, label=label, schema=LINEAGE_RUN_003_SCHEMA, lineage_name=LINEAGE_RUN_003,
                    exclude=exclude, copy_names=INIT_RUN_003_COPY, bindings=bindings, note=RUN_003_NOTE,
                    link=link, copy=copy)


