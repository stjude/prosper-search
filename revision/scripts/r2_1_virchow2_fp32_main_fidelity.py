def _coords(obj):
    return [np.asarray(d['wsi_loc']).tolist() for d in obj[1]]


def _check_fp32_obj(obj, tiles):
    probs = []
    if not (isinstance(obj, tuple) and len(obj) == 2):
        return ['not a 2-tuple']
    a = obj[0]
    if not isinstance(a, np.ndarray):
        return ['element 0 not numpy.ndarray']
    if a.dtype != np.float32:
        probs.append(f'dtype {a.dtype}')
    if a.ndim != 2:
        probs.append(f'ndim {a.ndim}')
    elif a.shape[1] != WIDTH:
        probs.append(f'width {a.shape[1]}')
    if not a.flags['C_CONTIGUOUS']:
        probs.append('not C-contiguous')
    if a.ndim == 2 and a.shape[0] != tiles:
        probs.append(f'rows {a.shape[0]} != canonical_tiles {tiles}')
    if not np.isfinite(a).all():
        probs.append('non-finite values')
    return probs


def per_tile_rel_l2(new, old):
    """#32 definition (r2_1_virchow2_fp32_extract_cli.compare_arrays): float64, ||new-old||_2 / ||old||_2 per row."""
    n64 = np.asarray(new, dtype=np.float64)
    o64 = np.asarray(old, dtype=np.float64)
    on = np.linalg.norm(o64, axis=1)
    if (on == 0).any():
        raise FidelityError('zero-norm reference row in rel-L2')
    return np.linalg.norm(n64 - o64, axis=1) / on


def bank_check(inv_rows, reconcile, af8, fidelity_prod, tmpf_dir, fp32_dir, progress=None):
    """Returns (m1_report, m2_report, failures). Streams one slide (TMPF + FP32) at a time."""
    fails1, fails2 = [], []
    inv = {str(r['slide_id']): r for r in inv_rows}
    tmpf_ids, fp32_ids = sorted_pkl_ids(tmpf_dir), sorted_pkl_ids(fp32_dir)
    # M1.0 set equality and dtype counts
    if set(tmpf_ids) != set(inv):
        fails1.append(f'M1.0: TMPF basename set != #29 slide_id set ({len(set(tmpf_ids) ^ set(inv))} differ)')
    dcount = {}
    for r in inv_rows:
        dcount[r['dtype']] = dcount.get(r['dtype'], 0) + 1
    if dcount != {'float16': N_FLOAT16, 'float32': N_FLOAT32}:
        fails1.append(f'M1.0: #29 dtype counts {dcount}')
    # M2.1
    if len(fp32_ids) != N_SLIDES:
        fails2.append(f'M2.1: FP32 has {len(fp32_ids)} *.pkl, expected {N_SLIDES}')
    if fp32_ids != tmpf_ids:
        fails2.append('M2.1: FP32 basename set/sorted order != TMPF')
    rec_json = sorted(os.path.basename(p) for p in glob.glob(os.path.join(fp32_dir, '*.record.json')))
    if any(p.endswith('.pkl') for p in rec_json):
        fails2.append('M2.1: a *.record.json sibling matches *.pkl')
    # M2.2 record-level
    slides = reconcile.get('slides', {})
    if reconcile.get('disposition') != 'COMPLETE_PASS':
        fails2.append(f'M2.2: #30 disposition {reconcile.get("disposition")!r}')
    if len(slides) != N_SLIDES:
        fails2.append(f'M2.2: #30 has {len(slides)} slides')
    af8_pass = bool(af8.get('PASS')) and af8.get('n_checked') == N_SLIDES and not af8.get('coords_mismatch_slides')
    per1, per2, m7_medians = {}, {}, []
    fp32_set = set(fp32_ids)
    for i, sid in enumerate(tmpf_ids):
        r = inv.get(sid)
        p_t = os.path.join(tmpf_dir, sid + '.pkl')
        with open(p_t, 'rb') as fh:
            bt = fh.read()
        st = {'sha256': hashlib.sha256(bt).hexdigest(), 'size': len(bt)}
        ot = pickle.loads(bt)
        del bt
        st['dtype'] = str(ot[0].dtype) if isinstance(ot, tuple) and isinstance(ot[0], np.ndarray) else None
        if r is None:
            st['problems'] = ['not in #29']
        else:
            st['problems'] = [f'{k} {st[k]} != #29 {r[k]}' for k in ('sha256', 'size', 'dtype') if st[k] != r[k]]
        if st['problems']:
            fails1.append(f'M1.0: {sid}: ' + '; '.join(st['problems']))
        per1[sid] = st
        if sid not in fp32_set:
            continue
        p_f = os.path.join(fp32_dir, sid + '.pkl')
        with open(p_f, 'rb') as fh:
            bf = fh.read()
        s2 = {'sha256': hashlib.sha256(bf).hexdigest()}
        of = pickle.loads(bf)
        del bf
        exp = slides.get(sid, {}).get('pickle_sha256')
        probs = []
        if s2['sha256'] != exp:
            probs.append(f'sha256 {s2["sha256"]} != #30 {exp}')
        probs += _check_fp32_obj(of, r['canonical_tiles'] if r else -1)
        try:
            same_coords = _coords(of) == _coords(ot)
        except Exception as e:     # noqa: BLE001 -- recorded as a STOP problem
            same_coords = False
            probs.append(f'coordinate read error {type(e).__name__}')
        if not same_coords:
            probs.append('coordinates/order differ from TMPF')
        s2['problems'] = probs
        if probs:
            fails2.append(f'M2: {sid}: ' + '; '.join(probs))
        # M2.5 descriptive
        if not probs:
            a32 = np.asarray(of[0])
            t32 = np.asarray(ot[0]).astype(np.float32)
            s2['stored_dtype_tmpf'] = st['dtype']
            s2['max_abs_vs_tmpf_f32'] = float(np.abs(a32.astype(np.float64) - t32.astype(np.float64)).max())
            try:
                rl = per_tile_rel_l2(a32, t32)
                s2['median_rel_l2_vs_tmpf_f32'] = float(np.median(rl))
                s2['max_rel_l2_vs_tmpf_f32'] = float(rl.max())
            except FidelityError as e:      # descriptive only (M2.5): record, do not STOP
                s2['rel_l2_note'] = str(e)
            if r is not None and r['dtype'] == 'float16':
                if ot[0].dtype != np.float16:
                    fails2.append(f'M2.5: {sid}: #29 dtype float16 but TMPF stored {ot[0].dtype}')
                else:
                    try:
                        m = float(np.median(per_tile_rel_l2(a32.astype(np.float16), ot[0])))
                        s2['m7_median_rel_l2_fp16'] = m
                        m7_medians.append(m)
                    except FidelityError as e:
                        s2['m7_note'] = str(e)
        per2[sid] = s2
        del ot, of
        if progress and (i + 1) % 100 == 0:
            progress(f'[bank-check] {i + 1}/{len(tmpf_ids)}')
    ref = fidelity_prod
    for k in M7_REFERENCE_KEY:
        ref = ref[k]
    m7 = float(np.median(m7_medians)) if m7_medians else None
    m7_rep = {'definition': ('per float16-stored slide (#29 dtype): median over tiles of float64 '
                             '||FP32.astype(float16) - TMPF||_2 / ||TMPF||_2 (#32 compare_arrays definition); '
                             'statistic = median of the per-slide medians'),
              'n_slides': len(m7_medians), 'value': m7, 'reference_32': ref,
              'reproduces_to_3_significant_figures': (m7 is not None and len(m7_medians) == N_FLOAT16
                                                      and sig3(m7) == sig3(ref)),
              'gate': 'reported to the lead; not a STOP (M2.5)'}
    m1 = {'stage': 'M1.0', 'n_tmpf': len(tmpf_ids), 'dtype_counts_29': dcount,
          'dtype_counts_observed': _count(v['dtype'] for v in per1.values()), 'per_slide': per1,
          'failures': fails1, 'pass': not fails1}
    m2 = {'stage': 'M2', 'n_fp32': len(fp32_ids), 'basenames_and_order_equal_tmpf': fp32_ids == tmpf_ids,
          'record_json_siblings': len(rec_json), 'reconcile_disposition': reconcile.get('disposition'),
          'reconcile_n_slides': len(slides), 'af8_mosaic_check_pass_all_2921': af8_pass,
          'm7_reproduction': m7_rep, 'per_slide': per2, 'failures': fails2, 'pass': not fails2}
    return m1, m2, fails1 + fails2


def _count(it):
    d = {}
    for x in it:
        d[str(x)] = d.get(str(x), 0) + 1
    return d


