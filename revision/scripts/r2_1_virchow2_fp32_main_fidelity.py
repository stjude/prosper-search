def probe_gate(method, out_text, provenance_dir, probe_indices, bob_failed_lines, census_rows, per_row,
               amendment=None):
    """M1.3. `amendment` (a {path, sha256} binding of AMENDMENT_003) switches method `ot` to the amended rule; per_row
    must then carry top10/top50 identity (per_probe_rows(..., rank_depths=(10, 50)))."""
    lsf = parse_lsf_out(out_text)
    obj, verdict = parse_cli_json_and_verdict(out_text)
    prov = sorted(os.path.basename(p) for p in glob.glob(os.path.join(provenance_dir, 'provenance_*.json')))
    want = sorted(f'provenance_{i}.json' for i in probe_indices)
    if amendment is not None and method != 'ot':
        raise FidelityError('AMENDMENT_003 applies to method ot only (BoB bar unchanged at 1e-6)')
    if amendment is None:
        checks = {'fidelity_line_pass': verdict == 'PASS', 'rc_0': lsf['rc'] == 0,
                  'max_rel_diff_lt_1e-6': obj.get('max_rel_diff') is not None and obj['max_rel_diff'] < BAR_REL}
    else:
        rows_ok = len(per_row) == len(probe_indices)       # non-vacuous per-row bar: one entry per probe row
        checks = {'max_rel_diff_lt_1e-5': obj.get('max_rel_diff') is not None and
                  obj['max_rel_diff'] < BAR_REL_OT_A003,
                  'per_row_max_rel_lt_1e-5': rows_ok and all(r.get('max_rel') is not None and
                                                             r['max_rel'] < BAR_REL_OT_A003 for r in per_row),
                  f'per_row_top{TOPK_A003}_identical': rows_ok and all(r.get(f'top{TOPK_A003}_identical') is True
                                                                      for r in per_row)}
        # F3 (impl_004 review): NaN / 1e6-sentinel pattern identical per row, gated in amended mode
        checks['sentinel_pattern_identical'] = rows_ok and all(r.get('sentinel_pattern_equal') is True and
                                                               r.get('nan_pattern_equal') is True for r in per_row)
    checks.update({'n_probe_rows_7': obj.get('n_probe_rows') == len(probe_indices) == 7,
                   'n_compared_cells_20440': obj.get('n_compared_cells') == 7 * (N_SLIDES - 1),
                   'provenance_exactly_7': prov == want,
                   'no_FAILED_stdout_line': not bob_failed_lines,
                   'no_Traceback': not any(r['Traceback'] for r in census_rows)})
    if amendment is None:
        bar_ok = checks['fidelity_line_pass'] and checks['rc_0'] and checks['max_rel_diff_lt_1e-6']
    else:
        bar_ok = checks['max_rel_diff_lt_1e-5'] and checks['per_row_max_rel_lt_1e-5'] and \
            checks[f'per_row_top{TOPK_A003}_identical']
        # F2 (impl_004 review): rule 5 waives only the frozen CLI's `FIDELITY: FAIL` line with rc 1 and an epilogue
        waived = verdict == 'FAIL' and lsf['rc'] == 1 and lsf['epilogue'] is True
        checks['cli_outcome_in_amended_waiver'] = waived
    nit = [r for r in census_rows if r['numItermax']]
    checks['no_numItermax_with_failed_bar'] = bar_ok or not nit
    checks['per_row_no_nan'] = all(r.get('no_nan') is True for r in per_row)                       # F7
    checks['per_row_n_live_eq_published'] = all(r.get('n_live_eq_published') is True for r in per_row)  # F7
    rep = {'stage': f'M1.3 {method}', 'cli_output': obj, 'fidelity_line': verdict, 'lsf': lsf,
           'provenance_files': prov, 'expected_provenance_files': want, 'failed_stdout_lines': bob_failed_lines,
           'stderr_census': [{k: v for k, v in r.items()} for r in census_rows],
           'numItermax_elements': [(r['job_id'], r['index'], r['numItermax_lines']) for r in nit],
           'per_row': per_row}
    if amendment is not None:
        # AMENDMENT_003 rule 5: the CLI verdict is recorded, not gating, only while rules 2-3 hold and the outcome is
        # the waived FAIL/rc 1; otherwise it gates
        superseded = bool(bar_ok) and waived
        if not superseded:
            checks['fidelity_line_pass'] = verdict == 'PASS'
            checks['rc_0'] = lsf['rc'] == 0
        rep.update({'amendment': amendment, 'cli_fidelity_line': verdict, 'cli_rc': lsf['rc'],
                    'cli_epilogue': lsf['epilogue'], 'cli_term_reason': lsf['term_reason'],
                    'cli_verdict_superseded_by_amendment_003': superseded,
                    'amended_bar': {'max_rel_lt': BAR_REL_OT_A003, 'top_k_identical': TOPK_A003, 'pass': bool(bar_ok)},
                    'per_row_max_rel_max': max((r['max_rel'] for r in per_row if r.get('max_rel') is not None),
                                               default=None),
                    'per_row_top10_identical': bool(per_row) and all(r.get('top10_identical') is True
                                                                     for r in per_row)})
    rep.update({'checks': checks, 'pass': all(checks.values()),
                'failures': [f'M1.3 {method}: {k}' for k, v in checks.items() if not v]})
    return rep


def per_probe_rows(sim_dir, published_unmasked, rank_depths=None):
    """Per-row max abs / rel and bit identity of each probe row file versus the published unmasked matrix.
    rank_depths (AMENDMENT_003): for each k, top<k>_identical = the stable ascending argsorts of the row's and the
    published row's live cells (same cells, published column order) agree over the first k positions."""
    ref = published_unmasked
    ref_index = [str(i) for i in ref.index]
    ref_cols = [str(c) for c in ref.columns]
    col_pos = {c: j for j, c in enumerate(ref_cols)}
    row_pos = {r: i for i, r in enumerate(ref_index)}
    vals = ref.to_numpy()
    out = []
    for p in sorted(glob.glob(os.path.join(sim_dir, 'similarity_*.pkl'))):
        qid = os.path.basename(p)[len('similarity_'):-len('.pkl')]
        with open(p, 'rb') as fh:
            row = pickle.load(fh)
        d = {str(o): float(x) for o, x in row}
        cols = [c for c in ref_cols if c in d]
        a = np.array([d[c] for c in cols])
        b = vals[row_pos[qid], [col_pos[c] for c in cols]]
        live = (a < SENTINEL) & (b < SENTINEL)
        diff = np.abs(a[live] - b[live])
        rel = diff / np.maximum(np.abs(b[live]), 1e-12)
        # F7: NaN is neither live nor sentinel; count it, and compare n_live with the published row's live count
        n_live_pub = int((vals[row_pos[qid]] < SENTINEL).sum())
        out.append({'slide_id': qid, 'n_cols': len(cols), 'n_live': int(live.sum()),
                    'n_nan': int(np.isnan(a).sum()), 'n_live_published': n_live_pub,
                    'no_nan': not bool(np.isnan(a).any()), 'n_live_eq_published': int(live.sum()) == n_live_pub,
                    'max_abs': float(diff.max()) if diff.size else None,
                    'max_rel': float(rel.max()) if rel.size else None,
                    'bit_identical_all_cols': bool(np.array_equal(a, b)),
                    'sentinel_pattern_equal': bool(np.array_equal(a >= SENTINEL, b >= SENTINEL)),
                    'row_pickle_bytes': os.path.getsize(p)})
        if rank_depths:
            oa = np.argsort(a[live], kind='stable')
            ob = np.argsort(b[live], kind='stable')
            neq = np.nonzero(oa != ob)[0]
            for k in rank_depths:
                out[-1][f'top{k}_identical'] = bool(oa.size >= k and np.array_equal(oa[:k], ob[:k]))
            out[-1]['first_differing_rank_0based'] = int(neq[0]) if neq.size else None
            out[-1]['nan_pattern_equal'] = bool(np.array_equal(np.isnan(a), np.isnan(b)))
    return out


