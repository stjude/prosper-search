"""R2.2-ALL Stage B: D1 re-aggregation of the Stage A manifests and gap coordinate files.

D1 (2026-11-13): eligible := generator ``cluster_locs`` union (``in_cluster_locs``).
The 2,775 non-fallback slides are read from ``stage_a/slides/`` (where ``eligible ==
in_cluster_locs`` must already hold; asserted) and the 3 fallback slides from
``stage_a/slides_option_i/`` (regenerated by the 3-slide agent under D1).

Per slide, D4 source codes over the eligible set:
  0 = mosaic bank (fp32)           : eligible & in_mosaic
  1 = fully-tissue bank (fp16-ac)  : eligible & in_full_bank & ~in_mosaic
  2 = gap (new fp32)               : eligible & ~in_mosaic & ~in_full_bank

``shard`` (LSF array task) writes ``slides/<id>.json`` and, for non-fallback slides with a
gap, ``coords/<id>.coords.csv.gz`` (grid order). ``merge`` (local, small) combines the
per-slide jsons into ``summary.json`` / ``per_slide.csv`` and asserts the totals.
Stage A outputs are only read.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import stage_b_lib as L  # noqa: E402


def slide_record(slide, manifest_path, slide_json_path, is_fallback):
    df = L.read_manifest(manifest_path)
    meta = json.loads(Path(slide_json_path).read_text())
    elig = df["eligible"].to_numpy() == 1
    cl = df["in_cluster_locs"].to_numpy() == 1
    mos = df["in_mosaic"].to_numpy() == 1
    fb = df["in_full_bank"].to_numpy() == 1
    xy = df[["wsi_loc_x", "wsi_loc_y"]].to_numpy(np.int64)
    fails = []
    if not np.array_equal(elig, cl):
        fails.append(f"eligible!=in_cluster_locs ({int((elig != cl).sum())})")
    if np.any(mos & ~elig):
        fails.append(f"mosaic_outside_eligible ({int((mos & ~elig).sum())})")
    k = L.coord_key(xy)
    if len(np.unique(k)) != len(k):
        fails.append("duplicate_coords")
    code0 = elig & mos
    code1 = elig & fb & ~mos
    gap = L.gap_mask(df)
    if not np.array_equal(gap, elig & ~mos & ~fb):
        fails.append("gap_mask_mismatch")
    if int(code0.sum() + code1.sum() + gap.sum()) != int(elig.sum()):
        fails.append("codes_do_not_partition_eligible")
    cov = df["coverage"].to_numpy(np.float64)
    rec = {
        "slide": slide,
        "fallback": is_fallback,
        "manifest": str(manifest_path),
        "manifest_sha256": L.sha256_file(manifest_path),
        "stage_a_code_sha256": meta.get("code_sha256", {}),
        "n_eligible": int(elig.sum()),
        "n_code0_mosaic": int(code0.sum()),
        "n_code1_full_bank": int(code1.sum()),
        "n_code2_gap": int(gap.sum()),
        "n_gap_full": int((gap & (cov == 1.0)).sum()),
        "n_gap_partial": int((gap & (cov < 1.0)).sum()),
        "n_full_bank_not_eligible": int((fb & ~elig).sum()),
        "n_mosaic": int(mos.sum()),
        "failures": fails,
        "coords_file": None,
        "coords_sha256": None,
    }
    return rec, xy[gap], cov[gap]


def cmd_shard(args):
    run = Path(args.run)
    out = Path(args.out)
    (out / "slides").mkdir(parents=True, exist_ok=True)
    (out / "coords").mkdir(parents=True, exist_ok=True)
    slides = [s.strip() for s in Path(args.slides_file).read_text().split() if s.strip()]
    mine = slides[args.index::args.n]
    nfail = 0
    for s in mine:
        fb = s in L.FALLBACK_SLIDES
        d = run / "stage_a" / ("slides_option_i" if fb else "slides")
        rec, gxy, gcov = slide_record(s, d / f"{s}.manifest.csv.gz", d / f"{s}.json", fb)
        if rec["n_code2_gap"] and not fb:
            cp = out / "coords" / f"{s}.coords.csv.gz"
            rec["coords_file"] = str(cp)
            rec["coords_sha256"] = L.write_coords(cp, gxy, gcov)
        nfail += bool(rec["failures"])
        L.dump_json(out / "slides" / f"{s}.json", rec)
    print(f"shard {args.index}/{args.n}: {len(mine)} slides, {nfail} with failures")
    return 1 if nfail else 0


def cmd_merge(args):
    import pandas as pd
    out = Path(args.out)
    slides = [s.strip() for s in Path(args.slides_file).read_text().split() if s.strip()]
    recs = []
    missing = []
    for s in slides:
        p = out / "slides" / f"{s}.json"
        if not p.exists():
            missing.append(s)
            continue
        recs.append(json.loads(p.read_text()))
    df = pd.DataFrame([{k: v for k, v in r.items() if k not in ("stage_a_code_sha256", "failures")}
                       | {"failures": ";".join(r["failures"]),
                          "stage_a_slides_sha256": r["stage_a_code_sha256"].get("stage_a_slides.py", "")}
                       for r in recs])
    df.to_csv(out / "per_slide.csv", index=False)
    nf = df[~df.fallback]
    fbk = df[df.fallback]
    tot = {c: int(df[c].sum()) for c in ("n_eligible", "n_code0_mosaic", "n_code1_full_bank",
                                         "n_code2_gap", "n_gap_full", "n_gap_partial",
                                         "n_full_bank_not_eligible", "n_mosaic")}
    summary = {
        "n_slides_listed": len(slides),
        "n_slides_read": len(recs),
        "missing_slide_jsons": missing,
        "slides_with_failures": df.loc[df.failures != "", "slide"].tolist(),
        "totals_all": tot,
        "extraction_scope_non_fallback": {
            "n_slides_with_gap": int((nf.n_code2_gap > 0).sum()),
            "n_gap_tiles": int(nf.n_code2_gap.sum()),
            "n_coords_files": int(nf.coords_file.notna().sum()),
        },
        "fallback_slides": {str(r.slide): int(r.n_code2_gap) for r in fbk.itertuples()},
        "stage_a_slides_code_versions": sorted(df.stage_a_slides_sha256.unique().tolist()),
    }
    if args.expect_gap_total is not None:
        summary["expect_gap_total"] = args.expect_gap_total
        summary["gap_total_matches"] = tot["n_code2_gap"] == args.expect_gap_total
    if args.target_tiles:
        counts = dict(zip(nf.slide.astype(str), nf.n_code2_gap))
        tasks = L.pack_tasks(counts, args.target_tiles)
        loads = [int(sum(counts[s] for s in t)) for t in tasks]
        L.dump_json(out / "tasks.json", {"target_tiles": args.target_tiles, "tasks": tasks,
                                         "task_tiles": loads})
        summary["tasks"] = {"target_tiles": args.target_tiles, "n_tasks": len(tasks),
                            "max_task_tiles": max(loads), "min_task_tiles": min(loads)}
    L.dump_json(out / "summary.json", summary)
    print(json.dumps(summary, indent=1))
    ok = not missing and not summary["slides_with_failures"] and summary.get("gap_total_matches", True)
    return 0 if ok else 1


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("shard")
    a.add_argument("--run", required=True)
    a.add_argument("--out", required=True)
    a.add_argument("--slides-file", required=True)
    a.add_argument("--index", type=int, required=True)
    a.add_argument("--n", type=int, required=True)
    m = sub.add_parser("merge")
    m.add_argument("--out", required=True)
    m.add_argument("--slides-file", required=True)
    m.add_argument("--expect-gap-total", type=int)
    m.add_argument("--target-tiles", type=int)
    args = ap.parse_args(argv)
    return cmd_shard(args) if args.cmd == "shard" else cmd_merge(args)


if __name__ == "__main__":
    sys.exit(main())
