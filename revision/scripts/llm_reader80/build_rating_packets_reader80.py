"""S5d rating-packet builder (eight packets A-H of ten items). KEY-SIDE SCRIPT: reads case ids, cohorts and the
key; nothing it prints is for a rater.

Ported from `scripts/llm_pilot_round2/build_rating_packets_r2.py` (28878e3d...): same item content (payload as sent,
delivered text, first draft where the style revision changed it), same deterministic round-1 sentence splitter, same
rating-ID alphabet and code-substring exclusions, the same truth-free ordering constraint (E7-A3(1)), the same
verbatim §5 rubric paragraph of the round-1 specification (sha256 2a27ada7...), the same file set and form columns, the
same builder-text forbidden-string self-check. Differences required by plans 001/002 (S2, B1):
  * 80 items from the S0 freeze (inputs/), eight packets of ten (five CCDI-MCI + five STV each, random balanced
    split), one rater context per packet; instructions are byte-identical across packets.
  * rating IDs disjoint from rounds 1 and 2; one recorded seed drives IDs, split and order.
  * the instruction description is adapted to these payloads: "ten" nearest reference slides, the current case
    "with its label fields left empty" (these payloads are not masked: the query's own identifier is in the payload
    as sent), and the derived statistics described with the round-1 wording (the summaries were generated by the
    round-1 instruction module; statistics recomputed by S0 with the frozen round-1 function).
  * the example rating ID and the first-draft line are generic so the instructions are identical in every packet.
  * an extended leak scan of every rater-visible file (truth labels in query fields, case ids, cohort names,
    reader/study/round/version/instruction/pilot, file-system paths, other items' query identifiers).
Writes only <root>/rating_packet_A..H/ and <root>/rating_packet_key/; refuses to overwrite.
"""
from __future__ import annotations

import argparse
import csv
import io
import json
import random
import re
import secrets
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import reader80_common as C  # noqa: E402

FIRST_LABEL = "First draft (revised by the system's style check)"
RATER_FILES = ("RATING_INSTRUCTIONS.md", "packet.json", "packet.md", "rating_form.csv")
ROUND1_DERIVED_WORDING = (
    "Besides the payload, the system also passed the model a few statistics computed mechanically from the\n"
    "  payload (diagnosis counts and the most frequent diagnosis, mean/minimum/maximum similarity, the number of\n"
    "  discrepant neighbours) and a 200-word target. They add no information beyond the payload; a sentence that\n"
    "  restates them is checked against the payload, directly or by arithmetic.")
ALPH = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"
CODES = ["ACT", "ACC", "EWS", "LIVER", "MEL", "MISC", "MPNST", "MRT", "NB", "NF", "NORMAL", "OS", "RB", "RMS",
         "SS", "WT", "HB", "HCC", "CCS", "SJ", "CASE"]


def stem_of(sid):
    """Patient-level stem of a query identifier: STV '<16 hex>_<block>_...' -> the hex prefix; CCDI PB code -> itself."""
    m = re.match(r"^([0-9a-f]{15,16})_", sid)
    return m.group(1) if m else sid


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", type=Path, default=C.OUT_ROOT)
    ap.add_argument("--seed", type=int, default=None, help="default: drawn once with secrets.randbits(48)")
    a = ap.parse_args(argv)
    root = a.root
    seed = a.seed if a.seed is not None else secrets.randbits(48)
    rng = random.Random(seed)

    # ------------------------------------------------------------ load the S0 freeze (read-only)
    man = list(csv.DictReader(open(root / "inputs" / "manifest_reader80.csv")))
    key = {r["case_id"]: r for r in csv.DictReader(open(root / "key" / "scoring_key_DO_NOT_SEND.csv"))}
    runs = {json.loads(l)["case_id"]: json.loads(l) for l in open(root / "inputs" / "runs_reader80_truthstripped.jsonl")}
    assert len(man) == C.N_ITEMS == len(runs) == len(key)
    items = []
    for m in man:
        cid, sid = m["case_id"], m["slide_id"]
        pl_bytes = (root / "inputs" / "payloads" / f"{sid}_packet.json").read_bytes()
        assert C.sha(pl_bytes) == m["payload_file_sha256"], cid
        payload = json.loads(pl_bytes)
        r = runs[cid]["run"]
        assert r["query"] == sid and C.payload_sha12(payload) == r["payload_sha"] and r["accepted"] and not r["error"]
        text = (root / "inputs" / "texts" / f"{sid}.txt").read_bytes().decode("utf-8")
        assert text == r["text"] and C.sha(text.encode()) == m["text_sha256"], cid
        t = r["telemetry"]
        tf = t.get("text_first") if t.get("revision_applied") else None
        cc = payload["current_case"]
        assert all(cc.get(k) is None for k in ("tumor_group", "diagnosis", "discrepant", "evaluation")), cid
        items.append({"case_id": cid, "slide_id": sid, "cohort": m["cohort"], "payload": payload,
                      "payload_file_sha256": m["payload_file_sha256"], "text": text,
                      "text_first_if_different": tf if (tf is not None and tf != text) else None,
                      "ids": {sid, cc.get("comp_bio_id") or sid}, "stem": stem_of(sid)})
    cohorts = sorted({it["cohort"] for it in items})
    assert cohorts == ["CCDI-MCI", "STV"] and all(sum(it["cohort"] == c for it in items) == 40 for c in cohorts)

    # ------------------------------------------------------------ linkage relation (truth-free, E7-A3(1) adapted)
    relations = []
    for y in items:
        ser = json.dumps(y["payload"], ensure_ascii=False)
        for x in items:
            if x is y:
                continue
            for ident in sorted(x["ids"] | {x["stem"]}):
                pat = rf"(?<![A-Za-z0-9]){re.escape(ident)}(?![A-Za-z0-9])"
                for where, s in (("payload", ser), ("text", y["text"]), ("text_first", y["text_first_if_different"] or "")):
                    if re.search(pat, s):
                        relations.append({"before": x["case_id"], "after": y["case_id"], "identifier_kind":
                                          "slide/comp_bio id" if ident in x["ids"] else "patient stem", "where": where})
    edges = {(r_["before"], r_["after"]) for r_ in relations}
    stems = {}
    for it in items:
        stems.setdefault(it["stem"], []).append(it["case_id"])
    shared_stems = {k: v for k, v in stems.items() if len(v) > 1}

    # ------------------------------------------------------------ rating ids (disjoint from rounds 1-2), split, order
    prior = set()
    for p in (C.ROUND1 / "rating_packet_key" / "rating_id_map.csv", C.ROUND2 / "rating_packet_key" / "rating_id_map.csv"):
        prior |= {row["rating_id"] for row in csv.DictReader(open(p))}
    used, rid = set(prior), {}
    for it in items:
        while True:
            cand = "R-" + "".join(rng.choice(ALPH) for _ in range(4))
            if cand in used or any(c in cand[2:] for c in CODES):
                continue
            used.add(cand)
            rid[it["case_id"]] = cand
            break
    by_cohort = {c: [it["case_id"] for it in items if it["cohort"] == c] for c in cohorts}
    for c in cohorts:
        rng.shuffle(by_cohort[c])
    packet_of = {}
    for i, L in enumerate(C.PACKET_LETTERS):
        for c in cohorts:
            for cid in by_cohort[c][i * C.PER_COHORT_PER_PACKET:(i + 1) * C.PER_COHORT_PER_PACKET]:
                packet_of[cid] = L
    order, attempts = {}, {}
    for L in C.PACKET_LETTERS:
        members = [it["case_id"] for it in items if packet_of[it["case_id"]] == L]
        assert len(members) == C.ITEMS_PER_PACKET
        n = 0
        while True:
            n += 1
            perm = members[:]
            rng.shuffle(perm)
            pos = {u: i for i, u in enumerate(perm)}
            if all(pos[x] < pos[y] for (x, y) in edges if x in pos and y in pos):
                break
        order[L], attempts[L] = perm, n
    cross_packet_edges = [e for e in edges if packet_of[e[0]] != packet_of[e[1]]]

    # ------------------------------------------------------------ rubric and instructions (identical in every packet)
    para_lines, (i0, i1) = C.rubric_paragraph()
    quoted = "\n".join("> " + l if l else ">" for l in para_lines)
    ORDER_SENTENCE = ("The order of items has a constraint. Rate strictly in the given order and do not go back to "
                      "change an earlier rating after reading a later item.")
    NO_ORDER_SENTENCE = ("Rate strictly in the given order and do not go back to change an earlier rating after "
                         "reading a later item.")
    any_within_edges = any(packet_of[x] == packet_of[y] for (x, y) in edges)
    instructions = f"""# Rating instructions

## What you are rating

Each item is one short summary written by a language model. With each summary you see the input the model
was given for that case (the "payload": the current case with its label fields left empty, its ten nearest
reference slides with their labels, sites and similarity values, and the neighbour-based probability line). For
every sentence of the summary, decide whether what it says is supported by the input shown, and record that in
`rating_form.csv`.

You rate each summary against its own payload only, not against what you may know about the case or the
reference library.

## Files

- `packet.md` (readable) and `packet.json` (same content, machine-readable): {C.ITEMS_PER_PACKET} items, in order.
  Each item has a rating ID (`R-` followed by four characters), the payload as sent, and the delivered
  summary split into numbered sentences.
- Some items may also show a "{FIRST_LABEL}". Rate its sentences too; they are numbered F1, F2, ... in the form.
- `rating_form.csv`: one row per sentence, with `rating_id`, `sentence_no` and `sentence_text` filled in.
  Fill in `code`, `probability_statement_tag` (leave empty if not a probability statement), `support_trace`
  and `note`. The file is UTF-8.
- Sentences were split mechanically (rule below). If a split looks wrong, rate the pieces as given and say
  so in `note`.

## Context for reading the payload

- The same fixed instructions were given to the model for every item (not reproduced here). Two field
  conventions stated in them, quoted: "similarity score (lower is better)" and "treatment=Y means treated, N
  means untreated".
- {ROUND1_DERIVED_WORDING}

## Rubric (contract section 5, quoted verbatim)

{quoted}

## Order

{ORDER_SENTENCE if any_within_edges else NO_ORDER_SENTENCE}

## Sentence-splitting rule

{C.SPLITTER_RULE}
"""
    item_by = {it["case_id"]: it for it in items}
    files_by_packet, counts = {}, {}
    for L in C.PACKET_LETTERS:
        packet = []
        for k, cid in enumerate(order[L], 1):
            it = item_by[cid]
            s = C.split_sentences(it["text"])
            tf = it["text_first_if_different"]
            sf = C.split_sentences(tf) if tf is not None else None
            packet.append({"position": k, "rating_id": rid[cid], "payload": it["payload"], "text": it["text"],
                           "text_first_if_different": tf,
                           "sentences": [{"sentence_no": j, "text": t} for j, t in enumerate(s, 1)],
                           "first_draft_sentences": (None if sf is None else
                                                     [{"sentence_no": f"F{j}", "text": t} for j, t in enumerate(sf, 1)])})
        files = {"packet.json": json.dumps(packet, ensure_ascii=False, indent=2) + "\n"}
        md = ["# Summary rating packet", "",
              f"{len(packet)} items, in the order to be rated. Read `RATING_INSTRUCTIONS.md` first. "
              "Record ratings in `rating_form.csv` (one row per numbered sentence).", ""]
        for it in packet:
            md += ["---", "", f'## Item {it["position"]} of {len(packet)} — {it["rating_id"]}', "",
                   "### Input shown to the model (payload, as sent)", "", "```json",
                   json.dumps(it["payload"], ensure_ascii=False, indent=2), "```", "", "### Summary (delivered)", ""]
            md += [f'{x["sentence_no"]}. {x["text"]}' for x in it["sentences"]] + [""]
            if it["first_draft_sentences"] is not None:
                md += [f"### {FIRST_LABEL}", ""]
                md += [f'{x["sentence_no"]}. {x["text"]}' for x in it["first_draft_sentences"]] + [""]
        files["packet.md"] = "\n".join(md)
        buf = io.StringIO()
        w = csv.writer(buf, lineterminator="\n")
        w.writerow(["rating_id", "sentence_no", "sentence_text", "code", "probability_statement_tag",
                    "support_trace", "note"])
        n_sent = n_first = 0
        for it in packet:
            for x in it["sentences"]:
                w.writerow([it["rating_id"], x["sentence_no"], x["text"], "", "", "", ""])
                n_sent += 1
            for x in it["first_draft_sentences"] or []:
                w.writerow([it["rating_id"], x["sentence_no"], x["text"], "", "", "", ""])
                n_first += 1
        files["rating_form.csv"] = buf.getvalue()
        files["RATING_INSTRUCTIONS.md"] = instructions
        files_by_packet[L] = (files, packet)
        counts[L] = {"items": len(packet), "sentences_delivered": n_sent, "sentences_first_draft": n_first,
                     "form_rows": n_sent + n_first,
                     "items_with_first_draft": sum(it["first_draft_sentences"] is not None for it in packet),
                     "cohort_split": {c: sum(item_by[cid]["cohort"] == c for cid in order[L]) for c in cohorts},
                     "precedence_edges_within": sum(packet_of[x] == L and packet_of[y] == L for (x, y) in edges),
                     "rejection_sampling_attempts": attempts[L]}

    # ------------------------------------------------------------ self-checks: forbidden strings in builder text
    case_ids = sorted(item_by)
    truths = sorted({key[c]["true_group"] for c in case_ids})
    forbidden = ["a0_masked_posterior", "a1_opaque", "a2_cf_plurality", "repeat", "swap", "plurality",
                 "counterfactual", "leak", "flag", "warning", "S=",
                 "round", "rounds", "second", "version", "revised instruction", "new instruction", "pilot", "s5b",
                 "s5c", "pass 031", "previous", "differing",
                 "reader", "readers", "study", "CCDI", "STV", "MCI", "s5d", "reader80", "prosper", "PROSPER_OUT",
                 "/research", "/home", "cohort", "truth", "reference group", "true group", "pathologist"]
    substring_terms = set(forbidden[:11])

    def strip_items(s, packet):
        for it in packet:
            for t in [json.dumps(it["payload"], ensure_ascii=False, indent=2), it["text"], it["text_first_if_different"] or ""]:
                if t:
                    s = s.replace(t, "")
            for x in it["sentences"] + (it["first_draft_sentences"] or []):
                s = s.replace(x["text"], "")
        return s

    checks = {"a_forbidden_strings_builder_text": {}}
    for L, (files, packet) in files_by_packet.items():
        res_L = {}
        for f in RATER_FILES:
            s = files[f]
            if f == "RATING_INSTRUCTIONS.md":
                unq = s.replace(quoted, "").replace(C.SPLITTER_RULE, "")
            elif f == "packet.json":
                unq = json.dumps([{k: v for k, v in it.items() if k not in ("payload", "text", "text_first_if_different",
                                                                           "sentences", "first_draft_sentences")}
                                  for it in packet]) + " " + " ".join(sorted({k for it in packet for k in it}))
            else:
                unq = strip_items(s, packet)
            res = {}
            for term in forbidden + case_ids + truths:
                fl = re.IGNORECASE if term not in ("S=",) and term not in truths else 0
                pat = re.escape(term) if term in substring_terms or term.startswith("/") else rf"\b{re.escape(term)}\b"
                in_builder = bool(re.search(pat, unq, fl))
                n_total = len(re.findall(pat, s, fl))
                if n_total:
                    res[term] = {"total_hits": n_total, "in_builder_authored_text": in_builder}
                if term in truths:
                    continue  # group codes legitimately occur in builder text only if an ID contained one (excluded)
                assert not in_builder, (L, f, term)
            res_L[f] = res
        checks["a_forbidden_strings_builder_text"][L] = res_L

    # ------------------------------------------------------------ extended leak scan of every rater-visible file
    scan_terms = {
        "case_id (caseNNN)": r"(?i)\bcase0?\d{2,3}\b",
        "cohort name": r"(?i)\b(CCDI(-MCI)?|STV|MCI|COMET|cohort)\b",
        "reader/study/round/version/instruction/pilot": r"(?i)\b(reader\w*|stud(y|ies)|rounds?|version\w*|instruction\w*|pilot\w*)\b",
        "file-system path": r"(/research|/home|/tmp|/hpcf|prosper_revision|PROSPER_OUT|[A-Za-z]:\\\\)",
    }
    scan = {}
    for L, (files, packet) in files_by_packet.items():
        rows = []
        for f in RATER_FILES:
            s = files[f]
            if f == "RATING_INSTRUCTIONS.md":
                comps = {"builder-authored": s.replace(quoted, "").replace(C.SPLITTER_RULE, ""),
                         "verbatim rubric paragraph": quoted, "verbatim splitter rule": C.SPLITTER_RULE}
            else:
                if f == "packet.json":
                    b = json.dumps([{k: v for k, v in it.items() if k not in ("payload", "text", "text_first_if_different",
                                                                             "sentences", "first_draft_sentences")}
                                    for it in packet]) + " " + " ".join(sorted({k for it in packet for k in it}))
                    b += " " + " ".join(sorted({k for it in packet for x in it["sentences"] for k in x}))
                else:
                    b = strip_items(s, packet)
                comps = {"builder-authored": b}
                comps["payload as sent"] = "\n".join(json.dumps(it["payload"], ensure_ascii=False, indent=2) for it in packet)
                comps["model text (delivered)"] = "\n".join(it["text"] for it in packet)
                comps["model text (first draft)"] = "\n".join(it["text_first_if_different"] or "" for it in packet)
            for comp, txt in comps.items():
                for name, pat in scan_terms.items():
                    for m in re.finditer(pat, txt):
                        rows.append({"file": f, "term": name, "match": m.group(0), "where": comp,
                                     "context": (txt[max(0, m.start() - 40):m.end() + 40].replace("\n", " ")
                                                 if not comp.startswith("model text") else "(model text not echoed)")})
        # truth labels in the query fields; other items' query identifiers
        truth_in_query, foreign_ids = [], []
        for it in packet:
            cid = next(c for c in order[L] if rid[c] == it["rating_id"])
            tg = key[cid]["true_group"]
            cc = it["payload"]["current_case"]
            if any(v is not None and re.search(rf"\b{re.escape(tg)}\b", str(v)) for k, v in cc.items()
                   if k not in ("slide_id", "comp_bio_id")):
                truth_in_query.append(it["rating_id"])
            if any(cc.get(k) is not None for k in ("tumor_group", "diagnosis", "discrepant", "evaluation",
                                                   "sample_type", "treatment", "met", "ped_adult")):
                truth_in_query.append(it["rating_id"] + " (non-null label field)")
        allfiles = "\n".join(files.values())
        for other in items:
            if packet_of[other["case_id"]] == L:
                continue
            for ident in other["ids"]:
                if ident in allfiles:
                    foreign_ids.append(ident[:8] + "...")
        scan[L] = {"hits": rows, "truth_label_in_query_fields": truth_in_query,
                   "other_packets_query_ids_present": foreign_ids,
                   "n_hits_builder_authored": sum(r_["where"] == "builder-authored" for r_ in rows),
                   "n_hits_by_where": {w_: sum(r_["where"] == w_ for r_ in rows) for w_ in sorted({r_["where"] for r_ in rows})}}
        assert not truth_in_query and not foreign_ids, (L, truth_in_query, foreign_ids)

    # ------------------------------------------------------------ write (refuse to overwrite)
    KEY = root / "rating_packet_key"
    targets = [root / f"rating_packet_{L}" for L in C.PACKET_LETTERS] + [KEY]
    for t in targets:
        t.mkdir(parents=True, exist_ok=False)
    instr_sha = None
    for L, (files, packet) in files_by_packet.items():
        d = root / f"rating_packet_{L}"
        for f in RATER_FILES:
            (d / f).write_text(files[f], encoding="utf-8")
        with open(d / "sha256.txt", "w") as fh:
            for f in RATER_FILES:
                fh.write(f"{C.fsha(d / f)}  {f}\n")
        s_ = C.fsha(d / "RATING_INSTRUCTIONS.md")
        assert instr_sha in (None, s_)
        instr_sha = s_
    # sha256.txt scan (hash lines only)
    for L in C.PACKET_LETTERS:
        s = (root / f"rating_packet_{L}" / "sha256.txt").read_text()
        for name, pat in scan_terms.items():
            assert not re.search(pat, s), (L, name)
    with open(KEY / "rating_id_map.csv", "w", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["rating_id", "packet", "position", "case_id", "slide_id", "cohort", "run_uid", "arm",
                    "payload_file_sha256", "text_sha256", "has_first_draft"])
        for L in C.PACKET_LETTERS:
            for k, cid in enumerate(order[L], 1):
                it = item_by[cid]
                w.writerow([rid[cid], L, k, cid, it["slide_id"], it["cohort"], f"{it['slide_id']}_packet_0", "packet",
                            it["payload_file_sha256"], C.sha(it["text"].encode()),
                            it["text_first_if_different"] is not None])
    oc = {"seed": seed, "seed_source": "argument" if a.seed is not None else "secrets.randbits(48)",
          "rng": "random.Random(seed): rating IDs (item order case001..080), then cohort shuffles (CCDI-MCI, STV), "
                 "then per-packet rejection-sampled shuffles A..H",
          "relation": "X before Y iff X's query identifier (slide_id / comp_bio_id) or patient stem (STV hex prefix; "
                      "CCDI PB code) appears word-bounded in item Y's payload, delivered text or first draft "
                      "(E7-A3(1) rule adapted to unmasked payloads)",
          "raw_relations": relations, "precedence_edges": sorted(edges), "cross_packet_edges": cross_packet_edges,
          "shared_patient_stems_among_80": shared_stems,
          "packet_of": packet_of,
          "final_order": {L: [{"position": k, "rating_id": rid[c], "case_id": c} for k, c in enumerate(order[L], 1)]
                          for L in C.PACKET_LETTERS}}
    (KEY / "order_constraints.json").write_text(json.dumps(oc, indent=1, ensure_ascii=False) + "\n")
    checks.update({
        "c_counts": counts,
        "d_order": {"precedence_edges": len(edges), "cross_packet": len(cross_packet_edges),
                    "within_packet_satisfied": True, "attempts": attempts},
        "quoted_paragraph": {"contract": str(C.ROUND1_CONTRACT), "contract_lines": [i0 + 1, i1 + 1],
                             "sha256_of_paragraph": C.sha("\n".join(para_lines).encode()),
                             "equals_round1_quote": True},
        "rating_ids_disjoint_from_rounds_1_2": not (set(rid.values()) & prior),
        "instructions_identical_across_packets": instr_sha,
        "f_hashes_rater": {L: {f: C.fsha(root / f"rating_packet_{L}" / f) for f in RATER_FILES + ("sha256.txt",)}
                           for L in C.PACKET_LETTERS}})
    (KEY / "build_checks.json").write_text(json.dumps(checks, indent=1, ensure_ascii=False, default=str) + "\n")
    (KEY / "leak_scan.json").write_text(json.dumps(scan, indent=1, ensure_ascii=False) + "\n")
    summary = {"n_items": len(items), "packets": {L: counts[L] for L in C.PACKET_LETTERS},
               "n_sentences_delivered": sum(c["sentences_delivered"] for c in counts.values()),
               "n_sentences_first_draft": sum(c["sentences_first_draft"] for c in counts.values()),
               "n_precedence_edges": len(edges), "seed": seed, "script_sha256": C.fsha(Path(__file__)),
               "common_sha256": C.fsha(Path(C.__file__)),
               "round2_builder_sha256": C.fsha(C.R2_SCRIPTS / "build_rating_packets_r2.py"),
               "leak_scan_builder_authored_hits": {L: scan[L]["n_hits_builder_authored"] for L in C.PACKET_LETTERS}}
    (KEY / "build_summary.json").write_text(json.dumps(summary, indent=1) + "\n")
    C.write_sha_list(KEY)
    print(json.dumps(summary, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
